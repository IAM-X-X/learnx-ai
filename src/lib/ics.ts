'use client';

/** Generate and download an .ics calendar file from a study plan. */
export function downloadStudyPlanIcs(opts: {
  goal: string;
  dailyMinutes: number;
  tasks: { day: number; title: string; duration: string; focus: string; type: string }[];
}) {
  const { goal, tasks } = opts;
  const now = new Date();
  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//LearnX AI//Study Plan//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:LearnX AI — ${escapeIcs(goal)}`,
  ];

  for (const task of tasks) {
    const day = new Date(now);
    day.setDate(day.getDate() + (task.day - 1));
    day.setHours(9, 0, 0, 0); // default 9am
    // parse duration like "20 min" → minutes
    const mins = parseInt(task.duration, 10) || 30;
    const end = new Date(day.getTime() + mins * 60000);
    lines.push(
      'BEGIN:VEVENT',
      `UID:${task.day}-${Date.now()}@learnx.ai`,
      `DTSTAMP:${formatIcsDate(now)}`,
      `DTSTART:${formatIcsDate(day)}`,
      `DTEND:${formatIcsDate(end)}`,
      `SUMMARY:${escapeIcs(`Day ${task.day}: ${task.title}`)}`,
      `DESCRIPTION:${escapeIcs(`${task.focus}\n\nType: ${task.type}\nDuration: ${task.duration}\n\nGenerated by LearnX AI for: ${goal}`)}`,
      'END:VEVENT',
    );
  }

  lines.push('END:VCALENDAR');
  const blob = new Blob([lines.join('\r\n')], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `learnx-study-plan-${goal.replace(/[^a-z0-9]+/gi, '-').slice(0, 40).toLowerCase()}.ics`;
  a.click();
  URL.revokeObjectURL(url);
}

function formatIcsDate(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return (
    d.getUTCFullYear().toString() +
    pad(d.getUTCMonth() + 1) +
    pad(d.getUTCDate()) +
    'T' +
    pad(d.getUTCHours()) +
    pad(d.getUTCMinutes()) +
    pad(d.getUTCSeconds()) +
    'Z'
  );
}

function escapeIcs(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\n/g, '\\n');
}
